#!/usr/bin/env python3
"""Render docs/test-cases.md from a real test run (stdlib only).

    python scripts/test_report.py CASES.jsonl OUT.md JUNIT.xml [JUNIT.xml ...]

``CASES.jsonl`` holds the documented cases the ``case`` fixture recorded
(``TEST_CASES_OUTPUT``, see mocks/tests/conftest.py); the JUnit files list every test
that ran. ``python scripts/dev.py test-report`` runs both test environments and calls this.
"""

from __future__ import annotations

import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_cases(path: Path) -> list[dict]:
    cases = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            case = json.loads(line)
            cases[case["id"]] = case
    return sorted(cases.values(), key=lambda c: (c["suite"], c["id"]))


def load_junit(paths: list[Path]) -> dict[str, dict]:
    """Test id -> {file, name, outcome, seconds}. A later file's pass replaces an earlier skip."""
    tests: dict[str, dict] = {}
    for path in paths:
        for node in ET.parse(path).getroot().iter("testcase"):
            module = node.get("classname", "")
            if not module:
                continue  # a module skipped at collection (it runs in the other environment)
            file = module.replace(".", "/") + ".py"
            name = node.get("name", "")
            if node.find("failure") is not None or node.find("error") is not None:
                outcome = "failed"
            elif node.find("skipped") is not None:
                outcome = "skipped"
            else:
                outcome = "passed"
            key = f"{file}::{name}"
            if key in tests and outcome == "skipped":
                continue
            tests[key] = {"file": file, "name": name, "outcome": outcome, "seconds": float(node.get("time", 0))}
    return tests


def cell(value) -> str:
    if value is None:
        text = "null"
    elif isinstance(value, str):
        text = value
    else:
        text = json.dumps(value, ensure_ascii=False)
    return text.replace("|", "\\|").replace("\n", " ")


def code(value) -> str:
    return f"`{cell(value)}`"


def commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def render(cases: list[dict], tests: dict[str, dict]) -> str:
    when = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    counts = Counter(t["outcome"] for t in tests.values())
    lines = [
        "# Test cases and results",
        "",
        f"Generated by `python scripts/dev.py test-report` from a real run on {when} (commit `{commit()}`).",
        "Do not edit by hand; re-run the command after changing the mocks or tests.",
        "",
        "Each documented case runs against the real mock services in process: the mock MAE over its",
        "A2A HTTP+JSON routes, and the mock Energy Agent's workflow steps against the mock MAE and the",
        "mock price API. A case passes when every expected value matches the actual one. Actual values",
        "with no expected value are observations recorded for reference. Scenarios are chosen with",
        "`scenario=<name>` in the intent (or `metadata.mockScenario`); see",
        "[dev-environment.md](dev-environment.md#mock-mae).",
        "",
        "## Summary",
        "",
        "| Suite | Cases | Passed | Failed |",
        "|---|---|---|---|",
    ]
    by_suite: dict[str, list[dict]] = {}
    for case in cases:
        by_suite.setdefault(case["suite"], []).append(case)
    for suite, items in by_suite.items():
        passed = sum(1 for c in items if c["outcome"] == "passed")
        lines.append(f"| {suite} | {len(items)} | {passed} | {len(items) - passed} |")
    lines += [
        "",
        f"All tests in this run (documented cases plus unit tests): **{len(tests)}**, "
        f"{counts['passed']} passed, {counts['failed']} failed, {counts['skipped']} skipped.",
        "",
        "| ID | Case | LLD | Result |",
        "|---|---|---|---|",
    ]
    for case in cases:
        anchor = case["id"].lower()
        lines.append(f"| [{case['id']}](#{anchor}) | {cell(case['title'])} | {cell(case['lld'])} | "
                     f"{'Pass' if case['outcome'] == 'passed' else '**FAIL**'} |")

    for suite, items in by_suite.items():
        lines += ["", f"## {suite}"]
        for case in items:
            result = "Pass" if case["outcome"] == "passed" else "**FAIL**"
            lines += [
                "",
                f"### {case['id']}",
                "",
                f"**{cell(case['title'])}** ({result})",
                "",
                f"- LLD: {cell(case['lld'])}",
                f"- Test: `{case['test']}`",
                f"- Input: {code(case['input'])}",
            ]
            if case.get("failure"):
                lines.append(f"- Failure: {code(case['failure'])}")
            lines += ["", "| Check | Expected | Actual |", "|---|---|---|"]
            actual = case.get("actual") or {}
            for key, expected in case["expected"].items():
                lines.append(f"| {key} | {code(expected)} | {code(actual.get(key))} |")
            for key, value in actual.items():
                if key not in case["expected"]:
                    lines.append(f"| {key} (observed) | | {code(value)} |")

    lines += ["", "## All tests", "", "| File | Tests | Passed | Failed | Skipped |", "|---|---|---|---|---|"]
    files: dict[str, Counter] = {}
    for test in tests.values():
        files.setdefault(test["file"], Counter())[test["outcome"]] += 1
    for file, tally in sorted(files.items()):
        lines.append(f"| `{file}` | {sum(tally.values())} | {tally['passed']} | {tally['failed']} | "
                     f"{tally['skipped']} |")
    failed = [t for t in tests.values() if t["outcome"] == "failed"]
    if failed:
        lines += ["", "Failed tests:", ""] + [f"- `{t['file']}::{t['name']}`" for t in failed]
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    cases_path, out_path, *junit = (Path(arg) for arg in sys.argv[1:])
    cases = load_cases(cases_path)
    tests = load_junit(junit)
    out_path.write_text(render(cases, tests), encoding="utf-8")
    failed = sum(1 for c in cases if c["outcome"] != "passed") + sum(
        1 for t in tests.values() if t["outcome"] == "failed")
    print(f"wrote {out_path}: {len(cases)} documented cases, {len(tests)} tests, {failed} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
